import { MemorySnapshot, StoredDirectory, StoredFile } from './storage';

/**
 * Renders a MemorySnapshot into a single deterministic Markdown document.
 *
 * This is the frozen injection artifact for the memory-validation experiment:
 * the same snapshot must always produce byte-identical output, so that the only
 * variable across experiment trials is presence/absence of the map, never its
 * formatting. Keep this pure and ordering-stable.
 */
export function renderMemoryMarkdown(projectName: string, snapshot: MemorySnapshot): string {
    const lines: string[] = [];
    lines.push(`# Project Memory: ${projectName}`);
    lines.push('');
    lines.push('_Generated by Atlas from `.atlas/memory.db`. Structural map only._');
    lines.push('');
    lines.push(
        `_${snapshot.directories.length} directories, ${snapshot.files.length} files, ` +
            `${snapshot.dependencies.length} dependencies._`
    );
    lines.push('');
    lines.push('## Structure');
    lines.push('');
    renderTree(lines, snapshot, null, 0);

    if (snapshot.dependencies.length > 0) {
        lines.push('');
        lines.push('## Dependencies');
        const manifests = Array.from(new Set(snapshot.dependencies.map((d) => d.sourceManifest))).sort();
        for (const manifest of manifests) {
            lines.push('');
            lines.push(`### ${manifest}`);
            lines.push('');
            for (const dep of snapshot.dependencies.filter((d) => d.sourceManifest === manifest)) {
                lines.push(`- ${dep.name}${dep.version ? ` ${dep.version}` : ''}`);
            }
        }
    }

    lines.push('');
    return lines.join('\n');
}

function renderTree(lines: string[], snapshot: MemorySnapshot, parentPath: string | null, depth: number): void {
    const indent = '  '.repeat(depth);

    const directories = sortByPath(snapshot.directories.filter((d) => d.parentPath === parentPath));
    const files = sortByPath(snapshot.files.filter((f) => f.parentPath === parentPath));

    for (const directory of directories) {
        lines.push(`${indent}- ${baseName(directory.path)}/`);
        renderTree(lines, snapshot, directory.path, depth + 1);
    }
    for (const file of files) {
        lines.push(`${indent}- ${baseName(file.path)}`);
    }
}

function sortByPath<T extends { path: string }>(entries: T[]): T[] {
    return [...entries].sort((a, b) => a.path.localeCompare(b.path));
}

function baseName(relativePath: string): string {
    const separatorIndex = relativePath.lastIndexOf('/');
    return separatorIndex === -1 ? relativePath : relativePath.slice(separatorIndex + 1);
}
